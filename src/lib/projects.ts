/** Every case, hidden ones included: case pages and old links keep working. */
export const allProjects = projectCatalog.sort((left, right) => left.index.localeCompare(right.index));
/** The cases the site shows: home page, catalogue and sitemap. */
export const projects = allProjects.filter((project) => !project.hidden);

export function getProject(slug: string) {
  return allProjects.find((project) => project.slug === slug);
}

export function filterProjects(category: (typeof projectCategories)[number]) {
  return category === "Все" ? projects : projects.filter((project) => project.category.includes(category));
}
